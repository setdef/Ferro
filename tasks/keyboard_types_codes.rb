require "json"
require "open3"

# Generates ferro-global-hotkey's Hotkey::Code from keyboard-types' source.
#
# keyboard-types' +Code+ has 216 variants, each with its rustdoc. Writing
# the Ruby constants by hand would invite a missed or misordered one, so
# <tt>rake codes:global-hotkey</tt> writes
# <tt>gems/global-hotkey/lib/ferro/global_hotkey/hotkey/code.rb</tt> from
# the keyboard-types that gem's Cargo.lock pins, and a tooling test checks
# the committed file is what this writes (plan 004, decision 8).
class KeyboardTypesCodes
  # One variant: its name, its rustdoc lines, and its deprecation note.
  Variant = Data.define(:name, :docs, :deprecated)

  # The generated file, relative to the repository.
  TARGET = "gems/global-hotkey/lib/ferro/global_hotkey/hotkey/code.rb"

  # The gem whose lockfile pins keyboard-types.
  GEM_DIR = "gems/global-hotkey"

  # The directory and version of the locked keyboard-types, read from
  # cargo metadata in +gem_dir+.
  def self.locked(gem_dir = GEM_DIR)
    output, status = Open3.capture2("cargo", "metadata", "--format-version", "1", "--offline", "--locked",
      chdir: gem_dir)
    raise "cargo metadata failed in #{gem_dir}" unless status.success?

    package = JSON.parse(output).fetch("packages").find { |entry| entry["name"] == "keyboard-types" }
    raise "#{gem_dir} does not lock keyboard-types" unless package

    [File.dirname(package.fetch("manifest_path")), package.fetch("version")]
  end

  # The variants of +Code+ in +source+, keyboard-types' <tt>src/code.rs</tt>,
  # in declaration order.
  def self.variants(source)
    body = source[/pub enum Code \{\n(.*?)\n\}/m, 1] or raise "no enum Code in the source"
    docs = []
    deprecated = nil
    body.each_line.filter_map do |line|
      text = line.strip
      if text.start_with?("///")
        docs << text.sub(%r{\A/// ?}, "")
        nil
      elsif text.start_with?("#[deprecated")
        deprecated = text[/"(.*)"/, 1]
        nil
      elsif text.start_with?("#[") || text.empty? then nil
      elsif (name = text[/\A([A-Za-z0-9]+),\z/, 1])
        variant = Variant.new(name:, docs:, deprecated:)
        docs = []
        deprecated = nil
        variant
      else raise "unrecognized line in enum Code: #{text}"
      end
    end
  end

  # A rustdoc line as RDoc: links become the variant's name, +kbd+
  # becomes +tt+, and HTML entities their characters.
  def self.rdoc(line)
    line.gsub(/\[`([A-Za-z0-9]+)`\]\[Code::\1\]/) { Regexp.last_match(1) }
      .gsub(%r{<span class="unicode">(.*?)</span>}) { Regexp.last_match(1) }
      .gsub("<br/>", "; ")
      .gsub(%r{<kbd>(.*?)</kbd>}) { "<tt>#{Regexp.last_match(1)}</tt>" }
      .gsub("&lt;", "<").gsub("&gt;", ">").gsub("&amp;", "&")
  end

  # The constants, each with its documentation.
  def self.constants(variants)
    variants.each_with_index.map do |variant, index|
      docs = variant.docs.map { |line| rdoc(line) }
      docs = ["The key whose W3C code value is +#{variant.name}+; keyboard-types describes it no further."] if docs.empty?
      docs += ["", "Deprecated: #{variant.deprecated}."] if variant.deprecated
      comment = docs.map { |line| line.empty? ? "        #" : "        # #{line}" }.join("\n")
      "#{comment}\n        #{variant.name} = new(:#{variant.name}, #{index})\n"
    end.join("\n")
  end

  # The whole of code.rb for +variants+ of keyboard-types +version+.
  def self.render(variants, version)
    deprecated = variants.select(&:deprecated).map { |variant| ":#{variant.name}" }.join(", ")
    HEAD.gsub("@COUNT@", variants.size.to_s).gsub("@VERSION@", version) + constants(variants) +
      TAIL.gsub("@DEPRECATED@", deprecated)
  end

  # Writes code.rb from the locked keyboard-types.
  def self.write(root = Dir.pwd)
    dir, version = locked(File.join(root, GEM_DIR))
    File.write(File.join(root, TARGET), render(variants(File.read(File.join(dir, "src/code.rs"))), version))
  end

  HEAD = <<~'RUBY'
    # frozen_string_literal: true

    #--
    # SPDX-FileCopyrightText: 2026 Kerrick Long <me@kerricklong.com>
    # SPDX-License-Identifier: Apache-2.0 OR MIT
    #++

    #--
    # Generated by tasks/keyboard_types_codes.rb (rake codes:global-hotkey)
    # from keyboard-types @VERSION@ src/code.rs. Do not edit by hand.
    #++

    module Ferro
      module GlobalHotkey
        module Hotkey
          # The physical position of a key.
          #
          # A shortcut names a key, but "the key" means different things: the
          # character it types depends on the layout, so <tt>Z</tt> on a US
          # keyboard is <tt>Y</tt> on a German one. A global shortcut wants the
          # key in the same place on every keyboard.
          #
          # A Code names that place. The names are based on the US keyboard.
          # If the key is not present on US keyboards, a name from another
          # layout is used. Each of the @COUNT@ constants is one of keyboard-types'
          # variants, after the W3C specification
          # (https://w3c.github.io/uievents-code/), in keyboard-types' order,
          # which is the order <tt><=></tt> uses. +Hyper+, +Super+, and +Turbo+
          # are deprecated, so naming one warns when
          # <tt>Warning[:deprecated]</tt> is on.
          #
          # Not every platform can register every key: macOS has no code for
          # F21 to F35, for one. Registering such a key raises
          # Error::FailedToRegister.
          #
          # Mirrors keyboard-types' +Code+ (<tt>src/code.rs:13-489</tt>), which
          # global-hotkey re-exports as <tt>hotkey::Code</tt>.
          #
          # === Examples
          #
          #   code = Ferro::GlobalHotkey::Hotkey::Code
          #   code::KeyQ.to_s # => "KeyQ"
          #   code.from_str("F19") # => code::F19
          #   code::KeyA < code::KeyB # => true
          class Code
            include Comparable

            private_class_method :new

            # Creates the code named +name+ at +index+ in keyboard-types'
            # order. The constants are the only instances.
            #
            # [name] Symbol, the keyboard-types variant's name.
            # [index] Integer, its discriminant.
            def initialize(name, index)
              @name = name
              @index = index
              freeze
            end

            # The code's W3C name, keyboard-types' +Display+ text.
            #
            # === Example
            #
            #   Ferro::GlobalHotkey::Hotkey::Code::KeyA.to_s # => "KeyA"
            def to_s
              @name.to_s
            end

            # The constant that holds this code.
            #
            # === Example
            #
            #   Ferro::GlobalHotkey::Hotkey::Code::KeyA.inspect # => "Ferro::GlobalHotkey::Hotkey::Code::KeyA"
            def inspect
              "Ferro::GlobalHotkey::Hotkey::Code::#{@name}"
            end

            # Orders codes as keyboard-types derives +Ord+: by their place in
            # its list. +nil+ for anything but a Code.
            #
            # [other] Object.
            #
            # === Example
            #
            #   Ferro::GlobalHotkey::Hotkey::Code::KeyA <=> Ferro::GlobalHotkey::Hotkey::Code::KeyB # => -1
            def <=>(other)
              @index <=> other.index if other.is_a?(Code)
            end

            # The code's name, for Marshal: a dumped code loads as the same
            # constant, so it keeps its identity, order, and hash.
            #
            # === Example
            #
            #   Marshal.load(Marshal.dump(Ferro::GlobalHotkey::Hotkey::Code::KeyA)).equal?(Ferro::GlobalHotkey::Hotkey::Code::KeyA) # => true
            def _dump(_level)
              @name.to_s
            end

            # The constant named +name+, for Marshal.
            #
            # [name] String, a dumped code's name.
            #
            # === Example
            #
            #   Ferro::GlobalHotkey::Hotkey::Code._load("KeyA") # => Ferro::GlobalHotkey::Hotkey::Code::KeyA
            def self._load(name)
              from_str(name)
            end

            # The code's place in keyboard-types' list.
            protected attr_reader :index

            # The Code named +string+, by keyboard-types' +FromStr+: its exact
            # W3C name, such as <tt>"KeyA"</tt>. Anything else raises
            # UnrecognizedCodeError.
            #
            # [string] String.
            #
            # === Example
            #
            #   Ferro::GlobalHotkey::Hotkey::Code.from_str("Space") # => Ferro::GlobalHotkey::Hotkey::Code::Space
            def self.from_str(string)
              ALL.fetch(GlobalHotkey.__send__(:settle, Native.code_from_str(string)))
            end

            #--
            # SPDX-SnippetBegin
            # SPDX-License-Identifier: MIT OR Apache-2.0
            # SPDX-SnippetCopyrightText: 2017 Pyfisch
            # SPDX-SnippetComment: Code's variants and their docs from
            #   keyboard-types @VERSION@ src/code.rs:13-489
            #++

  RUBY

  TAIL = <<~RUBY

            #--
            # SPDX-SnippetEnd
            #++

            # Every code, in keyboard-types' order.
            ALL = constants(false).map { |name| const_get(name, false) }.select { |value| value.is_a?(Code) }.sort.freeze
            private_constant :ALL

            deprecate_constant @DEPRECATED@
          end
        end
      end
    end
  RUBY
end
